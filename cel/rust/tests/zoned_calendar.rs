/// The ends of ECMAScript's time range: past them nothing answers, and near them a wall
/// clock past the range makes `Date.UTC` NaN, which Node writes as an offset of `-NaN:NaN`.
#[test]
fn the_ends_of_the_time_range() {
    assert_eq!(answer_line("Pacific/Kiritimati", 253_402_300_799_999), "10000,1,1,13,59,59|10000-01-01|10000-01-01T13:59:59.999+14:00|253402300799000|253402250400000|253402302599000");
    assert_eq!(answer_line("Pacific/Kiritimati", 8_640_000_000_000_000), "275760,9,13,14,0,0|275760-09-13|275760-09-13T14:00:00.000-NaN:NaN|!|8639998912800000|!");
    assert_eq!(answer_line("America/Los_Angeles", 8_640_000_000_000_000), "275760,9,12,17,0,0|275760-09-12|275760-09-12T17:00:00.000-07:00|8640000000000000|8639998988400000|!");
    assert_eq!(answer_line("UTC", 8_640_000_000_000_001), "!|!|!|!|!|!");
    assert_eq!(answer_line("UTC", -8_640_000_000_000_001), "!|!|!|!|!|!");
    assert_eq!(iso_text_in(8_640_000_000_000_000, "UTC").as_deref(), Some("+275760-09-13T00:00:00.000Z"));
    assert_eq!(date_text_in(-8_640_000_000_000_000, "UTC").as_deref(), Some("-271821-04"));
    assert_eq!(civil_time_in(0, "Mars/Olympus"), None);
    assert_eq!(instant_of_civil_time(&at(2026, 1, 1, 0, 0, 0), "Mars/Olympus"), None);
}

/// A wall clock a gap skips moves forward out of it and keeps its day — Chile skips
/// 2026-09-06 00:00–01:00, Cuba 2026-03-08 00:00–01:00, New York 2026-03-08 02:00–03:00 —
/// and one that occurs twice takes the earlier instant: New York's 2026-11-01 01:30.
#[test]
fn the_solver_moves_out_of_a_gap_and_takes_the_earlier_of_two() {
    assert_eq!(instant_of_civil_time(&at(2026, 9, 6, 0, 0, 0), "America/Santiago"), Some(1_788_667_200_000));
    assert_eq!(instant_of_civil_time(&at(2026, 3, 8, 0, 0, 0), "America/Havana"), Some(1_772_946_000_000));
    assert_eq!(instant_of_civil_time(&at(2026, 3, 8, 2, 30, 0), "America/New_York"), Some(1_772_955_000_000));
    assert_eq!(instant_of_civil_time(&at(2026, 11, 1, 1, 30, 0), "America/New_York"), Some(1_793_511_000_000));
    for &(zone, [year, month, day, hour, minute, second], instant) in SOLVED {
        assert_eq!(instant_of_civil_time(&at(year, month, day, hour, minute, second), zone), instant, "{zone} {year}-{month}-{day} {hour}:{minute}:{second}");
    }
}

/// Interim, Node's: the first candidate, from the offset at the wall clock read as UTC,
/// wins whenever its offset reads back unchanged, and that decides every wall clock that
/// occurs twice — the earlier instant west of UTC, the later east of it and in London, on
/// standard time. `zoned-calendar.ts`'s promise of the earlier is reached only where both
/// candidates read back, which no wall clock of the bundled database does.
#[test]
fn a_repeated_wall_clock_east_of_utc_takes_the_later_instant() {
    for (zone, fields, instant) in [
        ("Europe/Brussels", at(2026, 10, 25, 2, 30, 0), 1_792_891_800_000),
        ("Europe/London", at(2026, 10, 25, 1, 30, 0), 1_792_891_800_000),
        ("Australia/Sydney", at(2026, 4, 5, 2, 30, 0), 1_775_320_200_000),
        ("Australia/Lord_Howe", at(2026, 4, 5, 1, 45, 0), 1_775_315_700_000),
        ("America/New_York", at(2026, 11, 1, 1, 30, 0), 1_793_511_000_000),
        ("America/Santiago", at(2026, 4, 4, 23, 30, 0), 1_775_356_200_000),
    ] {
        assert_eq!(instant_of_civil_time(&fields, zone), Some(instant), "{zone}");
    }
    assert_eq!(iso_text_in(1_792_891_800_000, "Europe/Brussels").as_deref(), Some("2026-10-25T02:30:00.000+01:00"));
    assert_eq!(iso_text_in(1_793_511_000_000, "America/New_York").as_deref(), Some("2026-11-01T01:30:00.000-04:00"));
}

