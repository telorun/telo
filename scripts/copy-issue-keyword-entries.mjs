#!/usr/bin/env node
// Copies `sdk/issue-keywords/*.json` into `@telorun/sdk`'s source tree.
//
// The vocabulary is canonical at `sdk/issue-keywords/`, beside the other
// built-in data, so a second language half reads the same files rather than a
// restated list. TypeScript can only import a JSON file from inside its own
// package, so the Node half gets a copy — gitignored, with the barrel emitted
// from the same directory listing. Precedent: `copy-error-code-entries.mjs`.
//
// Usage: node scripts/copy-issue-keyword-entries.mjs

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "sdk", "issue-keywords");
const DEST = join(ROOT, "sdk", "nodejs", "src", "issue-keywords", "entries");

// A missing source directory is a packaging mistake, never an empty set: every
// finding would then be written as `invalid`.
if (!existsSync(SRC)) {
  console.error(
    `copy-issue-keyword-entries: '${SRC}' does not exist. The issue keywords are data ` +
      `that ships beside the language halves — if this is a container or package build, its ` +
      `file allowlist has to include 'sdk/issue-keywords'.`,
  );
  process.exit(1);
}

const names = readdirSync(SRC)
  .filter((f) => f.endsWith(".json"))
  .sort();

if (!names.includes("invalid.json")) {
  console.error(`copy-issue-keyword-entries: '${SRC}' declares no 'invalid' keyword.`);
  process.exit(1);
}

rmSync(DEST, { recursive: true, force: true });
mkdirSync(DEST, { recursive: true });

for (const name of names) {
  const text = readFileSync(join(SRC, name), "utf8");
  const entry = JSON.parse(text);
  if (`${entry.keyword}.json` !== name) {
    console.error(
      `copy-issue-keyword-entries: '${name}' declares keyword '${entry.keyword}'; the file must be named after its keyword.`,
    );
    process.exit(1);
  }
  writeFileSync(join(DEST, name), text, "utf8");
}

const imports = names
  .map((name, i) => `import e${i} from "./${name}" with { type: "json" };`)
  .join("\n");
const tuples = names.map((name, i) => `  ["${name}", e${i}],`).join("\n");

writeFileSync(
  join(DEST, "index.ts"),
  `// GENERATED by scripts/copy-issue-keyword-entries.mjs — do not edit, and do not commit.
// Source: sdk/issue-keywords/*.json (lexically ordered).
${imports}

/** Every issue keyword entry file, in lexical order. */
export const ISSUE_KEYWORD_ENTRY_FILES: ReadonlyArray<readonly [file: string, data: unknown]> = [
${tuples}
];
`,
  "utf8",
);

console.log(
  `copy-issue-keyword-entries: ${names.length} entr${names.length === 1 ? "y" : "ies"} → sdk/nodejs/src/issue-keywords/entries/`,
);
