//! The calendar in a time zone — `zoned-calendar.ts`: `known_time_zone`, `civil_time_in`,
//! `date_text_in`, `iso_text_in`, `instant_of_civil_time` and `days_in_month`.
//!
//! Every expected answer is Node's, executed: `@telorun/cel 0.129.0 at 2ee5ef49`, its
//! `knownTimeZone`, `civilTimeIn`, `dateTextIn`, `isoTextIn`, `instantOfCivilTime` and
//! `daysInMonth`, on Node v24.21.0 (V8 13.6.233.17-node.53, ICU 78.3, tz 2026c), whose zone
//! data is the bundled database's release (`jiff-tzdb` 0.1.8, tz 2026c); `uuid` 14.0.1 is
//! the slice's other pin. A `RangeError` or a `NaN` is `None`. The rows of *Where it
//! differs from Node* name Node's answer beside the engine's own. The solver's branches
//! the bundled database never reaches are pinned inside the crate, over synthetic readings.

use telorun_cel::{
    civil_time_in, date_text_in, days_in_month, instant_of_civil_time, iso_text_in, known_time_zone, CivilTime,
};

fn fnv(text: &str) -> u64 {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for byte in text.bytes() {
        hash ^= u64::from(byte);
        hash = hash.wrapping_mul(0x0100_0000_01b3);
    }
    hash
}

fn text(value: Option<impl ToString>) -> String {
    value.map_or("!".to_owned(), |value| value.to_string())
}

fn civil_text(civil: &CivilTime) -> String {
    format!("{},{},{},{},{},{}", civil.year, civil.month, civil.day, civil.hour, civil.minute, civil.second)
}

/// One instant's answers as the recording wrote them: the wall clock, the date, the ISO
/// text, and the instants solved for the wall clock itself, for midnight on the 1st of its
/// month and for its minute 30 later — `!` where Node threw.
fn answer_line(zone: &str, instant: i64) -> String {
    let civil = civil_time_in(instant, zone);
    let solve = |fields: Option<CivilTime>| fields.map_or("!".to_owned(), |fields| text(instant_of_civil_time(&fields, zone)));
    [
        civil.as_ref().map_or("!".to_owned(), civil_text),
        text(date_text_in(instant, zone)),
        text(iso_text_in(instant, zone)),
        solve(civil),
        solve(civil.map(|civil| CivilTime { day: 1, hour: 0, minute: 0, second: 0, ..civil })),
        solve(civil.map(|civil| CivilTime { minute: civil.minute + 30, ..civil })),
    ]
    .join("|")
}

fn at(year: i64, month: i64, day: i64, hour: i64, minute: i64, second: i64) -> CivilTime {
    CivilTime { year, month, day, hour, minute, second }
}

#[test]
fn every_bundled_zone_in_three_spellings() {
    let mut differing = Vec::new();
    for &(zone, transitions, digests) in ZONES {
        let mut instants = FIXED_INSTANTS.to_vec();
        for &transition in transitions {
            instants.extend([transition - 1_800_000, transition - 1, transition, transition + 999, transition + 1_800_000]);
        }
        for (spelling, digest) in [zone.to_owned(), zone.to_ascii_lowercase(), zone.to_ascii_uppercase()].iter().zip(digests) {
            let lines: Vec<String> = instants.iter().map(|&instant| answer_line(spelling, instant)).collect();
            if fnv(&lines.join("\n")) != digest {
                differing.push(spelling.clone());
            }
        }
    }
    assert_eq!(ZONES.len(), 597);
    assert!(differing.is_empty(), "answers differ from Node's for {differing:?}");
}

/// Every spelling here is answered as Node answers it: the engine's own and those near them.
