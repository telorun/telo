/// Node, over every `[+-]?HH:MM` with two digits each, accepts exactly the 2,880 signed
/// spellings with hours at most 23 and minutes at most 59.
#[test]
fn knows_every_signed_offset_to_23_59() {
    let mut accepted = 0;
    for sign in ["+", "-", ""] {
        for hours in 0..100 {
            for minutes in 0..100 {
                let zone = format!("{sign}{hours:02}:{minutes:02}");
                let known = !sign.is_empty() && hours <= 23 && minutes <= 59;
                assert_eq!(known_time_zone(&zone), known, "{zone}");
                accepted += usize::from(known);
            }
        }
    }
    assert_eq!(accepted, 2_880);
}

