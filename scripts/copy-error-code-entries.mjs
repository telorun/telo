#!/usr/bin/env node
// Copies `sdk/error-codes/*.json` into `@telorun/sdk`'s source tree.
//
// The entries are canonical at `sdk/error-codes/` because both kernels raise the
// ambient codes and must attach the same built-in texts to them, so a set written
// as one language's code would be a second copy drifting silently. Rust embeds the
// same files with `include_str!`. TypeScript can only import a JSON file from
// inside its own package, so the Node half gets a copy — gitignored, with the
// barrel emitted from the same directory listing. Precedent:
// `copy-zone-attribute-entries.mjs`.
//
// Usage: node scripts/copy-error-code-entries.mjs

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "sdk", "error-codes");
const DEST = join(ROOT, "sdk", "nodejs", "src", "error-codes", "entries");

// A missing source directory is a packaging mistake, never an empty set: every
// ambient error would then reach a person with no text.
if (!existsSync(SRC)) {
  console.error(
    `copy-error-code-entries: '${SRC}' does not exist. The built-in error codes are data ` +
      `that ships beside the language halves — if this is a container or package build, its ` +
      `file allowlist has to include 'sdk/error-codes'.`,
  );
  process.exit(1);
}

const names = readdirSync(SRC)
  .filter((f) => f.endsWith(".json"))
  .sort();

if (names.length === 0) {
  console.error(`copy-error-code-entries: '${SRC}' declares no error codes.`);
  process.exit(1);
}

rmSync(DEST, { recursive: true, force: true });
mkdirSync(DEST, { recursive: true });

for (const name of names) {
  const text = readFileSync(join(SRC, name), "utf8");
  const entry = JSON.parse(text);
  if (`${entry.code}.json` !== name) {
    console.error(`copy-error-code-entries: '${name}' declares code '${entry.code}'; the file must be named after its code.`);
    process.exit(1);
  }
  writeFileSync(join(DEST, name), text, "utf8");
}

const imports = names
  .map((name, i) => `import e${i} from "./${name}" with { type: "json" };`)
  .join("\n");
const tuples = names.map((name, i) => `  ["${name}", e${i}],`).join("\n");

writeFileSync(
  join(DEST, "index.ts"),
  `// GENERATED by scripts/copy-error-code-entries.mjs — do not edit, and do not commit.
// Source: sdk/error-codes/*.json (lexically ordered).
${imports}

/** Every built-in error code entry file, in lexical order. */
export const ERROR_CODE_ENTRY_FILES: ReadonlyArray<readonly [file: string, data: unknown]> = [
${tuples}
];
`,
  "utf8",
);

console.log(
  `copy-error-code-entries: ${names.length} entr${names.length === 1 ? "y" : "ies"} → sdk/nodejs/src/error-codes/entries/`,
);
