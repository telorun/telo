#!/usr/bin/env node
// Copies `sdk/value-types/*.json` into `@telorun/sdk`'s source tree.
//
// The entries are canonical at `sdk/value-types/` because every runtime that
// hosts Telo must read the IDENTICAL vocabulary — the Rust half types an
// `!include-bytes` slot from it in a kernel with no CEL engine — so a registry
// written as one language's code would be a second registry, hand-copied and
// drifting silently. Rust embeds the same files with `include_str!`; a Go half
// would use `//go:embed`. TypeScript can only import a JSON file from inside its
// own package (`rootDir`, and npm cannot pack a parent directory), so the Node
// half gets a copy.
//
// This is a COPY, not a generator: the bytes are identical, nothing is derived,
// so there is nothing that can drift into meaning something different from its
// source. The destination is gitignored — the repo holds one copy of each entry.
//
// Runs from `sdk/nodejs`'s `prepare`, which pnpm runs on workspace install and
// npm runs before pack/publish, so both a fresh clone and a published tarball
// have the files without anyone remembering a step. The precedent is
// `copy-migration-entries.mjs`, deliberately down to the barrel.
//
// Usage: node scripts/copy-value-type-entries.mjs

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "sdk", "value-types");
const DEST = join(ROOT, "sdk", "nodejs", "src", "value-types", "entries");

// A MISSING source directory is a packaging mistake, never an empty vocabulary.
// Emitting an empty barrel instead would ship a runtime in which every
// `x-telo-type` is an unknown name — the silent degrade this whole annotation
// exists to close, reappearing as a property of the build. It has happened
// already: a Dockerfile-local ignore allowlist named `sdk/nodejs` and not its
// sibling data directory, and the image shipped with no value types at all.
if (!existsSync(SRC)) {
  console.error(
    `copy-value-type-entries: '${SRC}' does not exist. The value-type vocabulary is ` +
      `data that ships beside the language halves — if this is a container or package ` +
      `build, its file allowlist has to include 'sdk/value-types'.`,
  );
  process.exit(1);
}

const names = readdirSync(SRC)
  .filter((f) => f.endsWith(".json"))
  // Lexical order is the set's order, so the vocabulary never depends on
  // whatever order the filesystem happened to return.
  .sort();

if (names.length === 0) {
  console.error(`copy-value-type-entries: '${SRC}' declares no value types.`);
  process.exit(1);
}

// Cleared rather than merged: a deleted entry must disappear from the copy, or
// retiring a value type would leave it registered.
rmSync(DEST, { recursive: true, force: true });
mkdirSync(DEST, { recursive: true });

for (const name of names) {
  const text = readFileSync(join(SRC, name), "utf8");
  // Parsed only to fail here rather than at `tsc`, where the error names a
  // copied path instead of the file someone actually edited.
  JSON.parse(text);
  writeFileSync(join(DEST, name), text, "utf8");
}

// The barrel. TypeScript has no glob import, so SOMETHING has to list the
// entries — and a hand-maintained list is the one place this mechanism could
// fail silently: add a file, forget the import, and the type is simply not in
// the vocabulary, which reads to an author as "unknown name". Emitting the list
// from the same directory listing that produced the copies makes the directory
// the single source of truth, so adding or retiring a type is genuinely one file.
const imports = names
  .map((name, i) => `import e${i} from "./${name}" with { type: "json" };`)
  .join("\n");
const tuples = names.map((name, i) => `  ["${name}", e${i}],`).join("\n");

writeFileSync(
  join(DEST, "index.ts"),
  `// GENERATED by scripts/copy-value-type-entries.mjs — do not edit, and do not commit.
// Source: sdk/value-types/*.json (lexically ordered).
${imports}

/** Every value-type entry file, in the order the registry reads them. */
export const VALUE_TYPE_ENTRY_FILES: ReadonlyArray<readonly [file: string, data: unknown]> = [
${tuples}
];
`,
  "utf8",
);

console.log(
  `copy-value-type-entries: ${names.length} entr${names.length === 1 ? "y" : "ies"} → sdk/nodejs/src/value-types/entries/`,
);
