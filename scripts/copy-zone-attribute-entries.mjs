#!/usr/bin/env node
// Copies `sdk/zone-attributes/*.json` into `@telorun/sdk`'s source tree.
//
// The entries are canonical at `sdk/zone-attributes/` because both kernels must
// agree on what an attribute MEANS — `noSuspend` is what stops a run parking
// inside a lease, wherever that run executes — so a vocabulary written as one
// language's code would be a second vocabulary, hand-copied and drifting
// silently. Rust embeds the same files with `include_str!`; a Go half would use
// `//go:embed`. TypeScript can only import a JSON file from inside its own
// package (`rootDir`, and npm cannot pack a parent directory), so the Node half
// gets a copy.
//
// This is a COPY, not a generator, and the destination is gitignored — the repo
// holds one copy of each entry. Direct precedent: `copy-value-type-entries.mjs`,
// deliberately down to the barrel.
//
// Usage: node scripts/copy-zone-attribute-entries.mjs

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "sdk", "zone-attributes");
const DEST = join(ROOT, "sdk", "nodejs", "src", "zone-attributes", "entries");

// A MISSING source directory is a packaging mistake, never an empty vocabulary.
// Shipping the empty barrel instead would make every declared attribute an
// unknown name — so a correct `noSuspend` would be reported as the author's typo
// while the constraint it expresses went unenforced. The value-type half has
// already been hit by exactly this (a container allowlist naming `sdk/nodejs`
// and not its sibling data directory).
if (!existsSync(SRC)) {
  console.error(
    `copy-zone-attribute-entries: '${SRC}' does not exist. The zone-attribute vocabulary ` +
      `is data that ships beside the language halves — if this is a container or package ` +
      `build, its file allowlist has to include 'sdk/zone-attributes'.`,
  );
  process.exit(1);
}

const names = readdirSync(SRC)
  .filter((f) => f.endsWith(".json"))
  // Lexical order is the set's order, so the vocabulary never depends on
  // whatever order the filesystem happened to return.
  .sort();

if (names.length === 0) {
  console.error(`copy-zone-attribute-entries: '${SRC}' declares no zone attributes.`);
  process.exit(1);
}

// Cleared rather than merged: a deleted entry must disappear from the copy, or
// retiring an attribute would leave it registered.
rmSync(DEST, { recursive: true, force: true });
mkdirSync(DEST, { recursive: true });

for (const name of names) {
  const text = readFileSync(join(SRC, name), "utf8");
  // Parsed only to fail here rather than at `tsc`, where the error names a
  // copied path instead of the file someone actually edited.
  JSON.parse(text);
  writeFileSync(join(DEST, name), text, "utf8");
}

// The barrel. TypeScript has no glob import, so SOMETHING has to list the
// entries — and a hand-maintained list is the one place this mechanism could
// fail silently: add a file, forget the import, and the attribute is simply not
// in the vocabulary, which reads to an author as "unknown name". Emitting the
// list from the same directory listing that produced the copies makes the
// directory the single source of truth.
const imports = names
  .map((name, i) => `import e${i} from "./${name}" with { type: "json" };`)
  .join("\n");
const tuples = names.map((name, i) => `  ["${name}", e${i}],`).join("\n");

writeFileSync(
  join(DEST, "index.ts"),
  `// GENERATED by scripts/copy-zone-attribute-entries.mjs — do not edit, and do not commit.
// Source: sdk/zone-attributes/*.json (lexically ordered).
${imports}

/** Every zone-attribute entry file, in the order the registry reads them. */
export const ZONE_ATTRIBUTE_ENTRY_FILES: ReadonlyArray<readonly [file: string, data: unknown]> = [
${tuples}
];
`,
  "utf8",
);

console.log(
  `copy-zone-attribute-entries: ${names.length} entr${names.length === 1 ? "y" : "ies"} → sdk/nodejs/src/zone-attributes/entries/`,
);
