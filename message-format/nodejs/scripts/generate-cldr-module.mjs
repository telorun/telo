/**
 * Writes `src/cldr-data.ts` from the tracked `message-format/cldr/` files: the three
 * data files as typed constants, under a `/*! *\/` Unicode License V3 notice that
 * TypeScript keeps and a bundler preserves as a legal comment. Run by `prepare` and
 * before every build, test and check, so the module is never older than the data.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const cldr = join(here, "..", "..", "cldr");
const target = join(here, "..", "src", "cldr-data.ts");

const license = readFileSync(join(cldr, "LICENSE"), "utf8").trimEnd();
if (license.includes("*/")) throw new Error("message-format/cldr/LICENSE holds */ and cannot sit in a /*! */ notice.");
const data = (name) => JSON.stringify(JSON.parse(readFileSync(join(cldr, name), "utf8")));

const text = `/*!
 * CLDR data (Unicode CLDR, https://cldr.unicode.org), used under this licence:

${license}
 */
// Generated by scripts/generate-cldr-module.mjs from message-format/cldr/; never edited by hand.
export const CLDR_PLURALS: CldrPluralsFile = ${data("plurals.json")};

export const CLDR_NUMBERS: CldrNumbersFile = ${data("numbers.json")};

export const CLDR_PARENT_LOCALES: CldrParentLocalesFile = ${data("parent-locales.json")};

// Last, so the notice above leads a statement the compiler keeps: a comment leading an
// elided type import is dropped with it.
import type { CldrNumbersFile, CldrParentLocalesFile, CldrPluralsFile } from "./cldr-tables.js";
`;

if (!existsSync(target) || readFileSync(target, "utf8") !== text) writeFileSync(target, text);
