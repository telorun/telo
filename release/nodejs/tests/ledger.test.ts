import { describe, expect, it } from "vitest";
import { parseLedger, serializeLedger } from "../src/ledger.js";

const LEDGER = `# Generated by \`release apply\` — what each unit looks like as published.
# A cache of the registries' answers, so a PR gate needs no credentials.
# \`release verify\` reconciles it against the registries.
units:
  kernel:
    version: 1.2.3
    layers:
      cargo:
        __proto__:
          lib: sha256-ccc
          src: sha256-ddd
        rust: sha256-aaa
      npm:
        __proto__: sha256-aaa
        nodejs: sha256-bbb
`;

describe("ledger", () => {
  it("keeps a __proto__ anchor as data through a round trip", () => {
    const entry = parseLedger(LEDGER, "ledger").units.get("kernel")!;
    const npm = entry.layers.ecosystems.npm!;
    expect(Object.keys(npm).sort()).toEqual(["__proto__", "nodejs"]);
    expect(Object.getOwnPropertyDescriptor(npm, "__proto__")?.value).toBe("sha256-aaa");
    const cargo = entry.layers.ecosystems.cargo!;
    expect(Object.getOwnPropertyDescriptor(cargo, "__proto__")?.value).toEqual({
      lib: "sha256-ccc",
      src: "sha256-ddd",
    });
    expect(serializeLedger(parseLedger(LEDGER, "ledger"))).toBe(LEDGER);
    expect(Object.prototype).not.toHaveProperty("lib");
    expect(Object.keys(Object.prototype)).toEqual([]);
  });
});
