#!/usr/bin/env node
// Copies `analyzer/formats/*.json` into `@telorun/analyzer`'s source tree.
//
// The entries are canonical at `analyzer/formats/` because every runtime must
// accept exactly the same strings at a slot declaring a Telo format. TypeScript
// can only import a JSON file from inside its own package, so the Node half gets
// a copy — the `copy-migration-entries.mjs` arrangement. The destination is
// gitignored; the repo holds one copy of each entry.
//
// Usage: node scripts/copy-format-entries.mjs

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "analyzer", "formats");
const DEST = join(ROOT, "analyzer", "nodejs", "src", "formats", "entries");

// A missing source directory is a packaging mistake: a build shipping no
// formats would stop checking every slot that declares one, silently.
if (!existsSync(SRC)) {
  console.error(
    `copy-format-entries: '${SRC}' does not exist. Format entries are data that ships ` +
      `beside the language halves — if this is a container or package build, its file ` +
      `allowlist has to include 'analyzer/formats'.`,
  );
  process.exit(1);
}

const names = readdirSync(SRC)
  .filter((f) => f.endsWith(".json"))
  .sort();

rmSync(DEST, { recursive: true, force: true });
mkdirSync(DEST, { recursive: true });

for (const name of names) {
  const text = readFileSync(join(SRC, name), "utf8");
  // Parsed here so a malformed entry names the file someone edited.
  JSON.parse(text);
  writeFileSync(join(DEST, name), text, "utf8");
}

const imports = names
  .map((name, i) => `import e${i} from "./${name}" with { type: "json" };`)
  .join("\n");
const tuples = names.map((name, i) => `  ["${name}", e${i}],`).join("\n");

writeFileSync(
  join(DEST, "index.ts"),
  `// GENERATED by scripts/copy-format-entries.mjs — do not edit, and do not commit.
// Source: analyzer/formats/*.json (lexically ordered).
${imports}

/** Every format entry file, in lexical order. */
export const FORMAT_ENTRY_FILES: ReadonlyArray<readonly [file: string, data: unknown]> = [
${tuples}
];
`,
  "utf8",
);

console.log(
  `copy-format-entries: ${names.length} entr${names.length === 1 ? "y" : "ies"} → analyzer/nodejs/src/formats/entries/`,
);
