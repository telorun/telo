//! Manifest migrations — the entry vocabulary. Mirrors `../../../nodejs/src/migrations/types.ts`.
//!
//! A migration is a MATCHER plus a PATCH, both data: the patch names what it targets, so
//! the driver derives whether a quick fix exists from the verb alone, and the matcher
//! selects every occurrence of a legacy spelling (`r#match.rs`). An entry contains no code,
//! which is what lets one entry file be read identically by every kernel.

use std::fmt;

use serde_json::Value;

use crate::types::DiagnosticSeverity;

use super::r#match::MigrationMatch;

/// One step of a location inside a manifest document: a mapping key or a sequence index.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum PathSegment {
    Key(String),
    Index(usize),
}

/// A location inside one manifest document.
pub type MigrationPath = Vec<PathSegment>;

/// What `set-tag` puts behind the tag: the scalar's text unchanged, or the expression of
/// the lone `${{ }}` hole the text is.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TagSource {
    Text,
    Hole,
}

/// What `set-value` writes: a literal scalar, or the existing string with a prefix.
#[derive(Debug, Clone, PartialEq)]
pub enum SetValue {
    Value(Value),
    Qualify(String),
}

/// The closed operation vocabulary, named for what each TARGETS.
#[derive(Debug, Clone, PartialEq)]
pub enum MigrationOperation {
    /// Rename the matched mapping entry's key within its own mapping; an occupied
    /// destination is refused rather than replaced.
    RenameKey { to: String },
    /// Replace the value at the match.
    SetValue(SetValue),
    /// Put the matched scalar behind a templating tag (`tag` without its `!`).
    SetTag { tag: String, source: TagSource },
    /// Insert an item into the matched sequence; `at` defaults to the end.
    InsertItem { value: Value, at: Option<usize> },
    /// Write a value under a key the matched mapping does not hold.
    AddKey { key: String, value: Value },
    /// Remove the matched mapping entry or sequence item.
    RemoveEntry,
}

/// The operation names, in the order an entry's refusal lists them.
pub const MIGRATION_OPS: [&str; 6] = ["rename-key", "set-value", "set-tag", "insert-item", "add-key", "remove-entry"];

/// One legacy spelling and the edit that replaces it.
#[derive(Debug, Clone)]
pub struct MigrationRule {
    pub r#match: MigrationMatch,
    /// Applied in order at each match; a patch that cannot apply in full applies not at all.
    pub patch: Vec<MigrationOperation>,
}

/// One deprecation story, possibly of several rules.
#[derive(Debug, Clone)]
pub struct MigrationEntry {
    pub id: String,
    /// Diagnostic code reported for every rewrite this entry makes.
    pub code: String,
    pub severity: DiagnosticSeverity,
    /// The rationale — the one part of the diagnostic the driver cannot generate.
    pub reason: String,
    pub rules: Vec<MigrationRule>,
}

/// One applied rewrite. Diagnostics are remapped through `legacy_path` before position
/// resolution, so a squiggle lands on what the author wrote.
#[derive(Debug, Clone, PartialEq)]
pub struct MigrationRewrite {
    pub entry_id: String,
    pub code: String,
    pub severity: DiagnosticSeverity,
    pub document_index: usize,
    /// Dotted path (`a.b[0].c`) as the author wrote it.
    pub legacy_path: String,
    /// Dotted path after the rewrite; equal to `legacy_path` unless a `rename-key` moved it.
    pub migrated_path: String,
    /// What changed, generated by the driver.
    pub summary: String,
}

/// Why a matched patch was refused. A migration that cannot rewrite leaves the node
/// untouched for the ordinary validator to reject.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MigrationRefusal {
    PathNotFound,
    DestinationOccupied,
    NotAMappingEntry,
    NotASequence,
    NotAMapping,
    NotAScalar,
    MalformedValue,
    /// The value is already what the patch would write: the matcher was too wide.
    NothingToRewrite,
}

/// A migration entry the reader refuses — the whole sentence Node's reader throws.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MigrationEntryError {
    pub message: String,
}

impl MigrationEntryError {
    pub fn new(message: impl Into<String>) -> Self {
        Self { message: message.into() }
    }
}

impl fmt::Display for MigrationEntryError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.message)
    }
}

impl std::error::Error for MigrationEntryError {}
