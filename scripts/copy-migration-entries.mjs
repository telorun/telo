#!/usr/bin/env node
// Copies `analyzer/migrations/*.json` into `@telorun/analyzer`'s source tree.
//
// The entries are canonical at `analyzer/migrations/` because every kernel must
// apply the IDENTICAL rewrite — a migration that succeeds is silent, so a
// divergence between two kernels would be invisible. A Rust reader is planned
// and will embed them there with `include_str!`; a Go half would use
// `//go:embed`. TypeScript can only import a JSON file from inside its own
// package (`rootDir`, and npm cannot pack a parent directory), so the Node half
// gets a copy.
//
// This is a COPY, not a generator: the bytes are identical, nothing is derived,
// so there is nothing that can drift into meaning something different from its
// source. The destination is gitignored — the repo holds one copy of each entry.
//
// Runs from `analyzer/nodejs`'s `prepare`, which pnpm runs on workspace install
// and npm runs before pack/publish, so both a fresh clone and a published
// tarball have the files without anyone remembering a step.
//
// Usage: node scripts/copy-migration-entries.mjs

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "analyzer", "migrations");
const DEST = join(ROOT, "analyzer", "nodejs", "src", "migrations", "entries");

const names = existsSync(SRC)
  ? readdirSync(SRC)
      .filter((f) => f.endsWith(".json"))
      // Lexical order is the set's order, so two entries never depend on
      // whatever order the filesystem happened to return.
      .sort()
  : [];

// Cleared rather than merged: a deleted entry must disappear from the copy, or
// retiring a migration would leave it running.
rmSync(DEST, { recursive: true, force: true });
mkdirSync(DEST, { recursive: true });

for (const name of names) {
  const text = readFileSync(join(SRC, name), "utf8");
  // Parsed only to fail here rather than at `tsc`, where the error names a
  // copied path instead of the file someone actually edited.
  JSON.parse(text);
  writeFileSync(join(DEST, name), text, "utf8");
}

// The barrel. TypeScript has no glob import, so SOMETHING has to list the
// entries — and a hand-maintained list is the one place this mechanism could
// fail silently: add a file, forget the import, and the migration never fires,
// which is indistinguishable from one that ran. Emitting the list from the same
// directory listing that produced the copies makes the directory the single
// source of truth, so adding or retiring an entry is genuinely one file.
const imports = names
  .map((name, i) => `import e${i} from "./${name}" with { type: "json" };`)
  .join("\n");
const tuples = names.map((name, i) => `  ["${name}", e${i}],`).join("\n");

writeFileSync(
  join(DEST, "index.ts"),
  `// GENERATED by scripts/copy-migration-entries.mjs — do not edit, and do not commit.
// Source: analyzer/migrations/*.json (lexically ordered).
${imports}

/** Every entry file, in the order the driver applies them. */
export const MIGRATION_ENTRY_FILES: ReadonlyArray<readonly [file: string, data: unknown]> = [
${tuples}
];
`,
  "utf8",
);

console.log(
  `copy-migration-entries: ${names.length} entr${names.length === 1 ? "y" : "ies"} → analyzer/nodejs/src/migrations/entries/`,
);
