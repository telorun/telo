#!/usr/bin/env node
// Writes modules/ui-lucide/telo.yaml from the lucide-static release of the Lucide
// version the lockfile's lucide-react resolves to: one `sources:` entry per glyph
// of the archive, and the same glyphs as the closed enum of `UiLucide.Icon.name`,
// so the names a manifest may write and the files the module ships are one list.
// Then pins every entry with `telo release stage --pin`. The generated manifest is
// checked in; edit this script, never the manifest, and run it again.
//
// Usage: node scripts/generate-ui-lucide-module.mjs [--no-pin]

import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync } from "node:zlib";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..");
const moduleDir = join(repoRoot, "modules", "ui-lucide");
const manifestPath = join(moduleDir, "telo.yaml");
const pin = !process.argv.includes("--no-pin");

const INITIAL_VERSION = "0.1.0";
const UPSTREAM = "lucide-static";
const URL_TEMPLATE = "https://registry.npmjs.org/{upstream}/-/{upstream}-{version}.tgz";

/** The one Lucide version the workspace's lucide-react resolves to. */
function lucideVersion() {
  const lock = readFileSync(join(repoRoot, "pnpm-lock.yaml"), "utf8");
  const versions = [...new Set([...lock.matchAll(/^  lucide-react@(\d+\.\d+\.\d+):$/gm)].map((match) => match[1]))];
  if (versions.length !== 1) throw new Error(`pnpm-lock.yaml resolves lucide-react to ${versions.length === 0 ? "no version" : versions.join(", ")}; expected exactly one`);
  return versions[0];
}

/** The member paths of a tar archive, pax `path` records applied. */
function tarMembers(archive) {
  const members = [];
  let longName;
  for (let at = 0; at + 512 <= archive.length; ) {
    const header = archive.subarray(at, at + 512);
    if (header.every((byte) => byte === 0)) break;
    const field = (from, to) => header.subarray(from, to).toString("utf8").replace(/\0[\s\S]*$/, "");
    const size = parseInt(field(124, 136).trim() || "0", 8);
    const type = String.fromCharCode(header[156] || 0x30);
    const body = archive.subarray(at + 512, at + 512 + size);
    if (type === "x") {
      longName = /(?:^|\n)\d+ path=([^\n]*)\n/.exec(body.toString("utf8"))?.[1];
    } else if (type !== "g") {
      const prefix = field(345, 500);
      const name = longName ?? (prefix ? `${prefix}/${field(0, 100)}` : field(0, 100));
      longName = undefined;
      if (type === "0" || type === "\0") members.push(name);
    }
    at += 512 + Math.ceil(size / 512) * 512;
  }
  return members;
}

async function glyphNames(version) {
  const url = URL_TEMPLATE.replaceAll("{upstream}", UPSTREAM).replaceAll("{version}", version);
  const response = await fetch(url);
  if (!response.ok) throw new Error(`GET ${url} answered ${response.status}`);
  const members = tarMembers(gunzipSync(Buffer.from(await response.arrayBuffer())));
  const names = members
    .map((member) => /^package\/icons\/([^/]+)\.svg$/.exec(member)?.[1])
    .filter((name) => name !== undefined)
    .sort();
  const unfit = names.filter((name) => !/^[a-z][a-z0-9-]*$/.test(name));
  if (unfit.length > 0) throw new Error(`glyph names outside [a-z][a-z0-9-]*, which the manifest writes unquoted: ${unfit.join(", ")}`);
  if (names.length === 0) throw new Error(`${url} holds no package/icons/*.svg`);
  return names;
}

/** A flow sequence wrapped under `indent`. */
function flowList(names, indent) {
  const lines = [];
  let line = "";
  for (const name of names) {
    const item = `${name}, `;
    if (line.length + item.length > 96) {
      lines.push(line.trimEnd());
      line = "";
    }
    line += item;
  }
  lines.push(line.replace(/, $/, ""));
  return `[\n${lines.map((each) => `${indent}  ${each}`).join("\n")}\n${indent}]`;
}

function manifest(version, names, previous) {
  const entry = (path, member) => {
    const kept = previous.pins.get(path);
    return `      ${path}: ${kept ?? `{ upstream: ${UPSTREAM}, member: ${member} }`}`;
  };
  return `# Generated by scripts/generate-ui-lucide-module.mjs from the lucide-static
# release of the Lucide version the lockfile's lucide-react resolves to. Edit the
# script and run it again; never edit this file.
kind: Telo.Library
metadata:
  name: UiLucide
  version: ${previous.version ?? INITIAL_VERSION}
  repository: https://github.com/telorun/telo
  license: MIT
  categories: [UI]
  description: >-
    Icons for declarative user interfaces: the ${names.length} open-source line
    glyphs of the Lucide set — home, settings, users, charts, files, arrows and
    more — named in the manifest and checked against the set before the app
    runs. Each is drawn in the colour of the text beside it in menus, sidebars
    and tab bars.
requires:
  # Imports ui, which needs 0.121.0.
  telo: ">=0.121.0"
imports:
  Ui: ../ui
exports:
  kinds:
    - Icon
# Every glyph ships in the assets layer; a resource reads only the one it names.
assets:
  - ./icons/
sources:
  lucide:
    version: ${version}
    url: ${URL_TEMPLATE}
    archive: tar.gz
    notices: [./notices/lucide.LICENSE]
    entries:
${entry("./notices/lucide.LICENSE", "package/LICENSE")}
${names.map((name) => entry(`./icons/${name}.svg`, `package/icons/${name}.svg`)).join("\n")}
---
kind: Telo.Definition
metadata:
  name: Icon
  description: >-
    One glyph of the Lucide icon set, named as Lucide names it, such as house,
    settings or chart-line; a name outside the set is refused before the app
    runs. Provides the glyph's SVG file, which a renderer paints in the colour
    of the text beside it.
capability: Telo.Provider
extends: Ui.Icon
controllers:
  - pkg:telo/local/js?path=./nodejs/ui-lucide.mjs&local_path=./nodejs/src/index.ts#IconController
schema:
  type: object
  additionalProperties: false
  required: [name]
  properties:
    name:
      title: Name
      description: The glyph's name in the Lucide set, as lucide.dev/icons lists it.
      type: string
      enum: ${flowList(names, "      ")}
`;
}

/** What a previous run left that a new one keeps: the released version, and
 *  each entry's pin while the Lucide version is unchanged. */
function previousOf(version) {
  const pins = new Map();
  if (!existsSync(manifestPath)) return { pins };
  const text = readFileSync(manifestPath, "utf8");
  const kept = text.match(/^  version: (\S+)$/m)?.[1];
  if (text.match(/^    version: (\S+)$/m)?.[1] === version) {
    for (const [, path, value] of text.matchAll(/^      (\.\/\S+): (\{ .*sha256: .*\})$/gm)) pins.set(path, value);
  }
  return { version: kept, pins };
}

const GITIGNORE = `# Staged from the \`sources:\` pin by \`telo release stage\`, and by the kernel on
# first use in a checkout.
/icons/
/notices/
`;

const version = lucideVersion();
const names = await glyphNames(version);
mkdirSync(moduleDir, { recursive: true });
writeFileSync(manifestPath, manifest(version, names, previousOf(version)));
writeFileSync(join(moduleDir, ".gitignore"), GITIGNORE);
if (!existsSync(join(moduleDir, "CHANGELOG.md"))) writeFileSync(join(moduleDir, "CHANGELOG.md"), "# Changelog\n");
copyFileSync(join(repoRoot, "modules", "LICENSE"), join(moduleDir, "LICENSE"));
console.log(`wrote ${relative(repoRoot, manifestPath)}: Lucide ${version}, ${names.length} glyphs`);

if (pin) {
  execFileSync("pnpm", ["run", "-s", "telo", "release", "stage", "--pin", "--module", relative(repoRoot, moduleDir)], {
    cwd: repoRoot,
    stdio: "inherit",
  });
}
